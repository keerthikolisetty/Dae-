from google.colab import drive

# Mount Google Drive
drive.mount('/content/drive')

# Read dataset from Google Drive
df = pd.read_csv('/content/drive/MyDrive/library management system dataset.csv')

# Filter for books that have been returned
returned_df = df[df['Return Status'] == 'Returned'].copy()

# Convert date columns to datetime objects (day-first format)
returned_df['Issue Date'] = pd.to_datetime(returned_df['Issue Date'], format='%d-%m-%Y')
returned_df['Return Date'] = pd.to_datetime(returned_df['Return Date'], format='%d-%m-%Y')

# Calculate Borrowing Days
returned_df['Borrowing Days'] = (returned_df['Return Date'] - returned_df['Issue Date']).dt.days

# Calculate average borrowing days
average_days = np.mean(returned_df['Borrowing Days'])

print("Average Borrowing Days:", average_days)

